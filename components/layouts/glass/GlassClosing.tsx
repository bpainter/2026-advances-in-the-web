import type { GlassContent, Slide } from "@/content/schema";

/** The closing slide (PRD v5, 4.6; spec 7): name, role and LinkedIn on dark glass, the QR on white. */
export function GlassClosing({ slide, content }: { slide: Slide; content: Extract<GlassContent, { kind: "closing" }> }) {
  return (
    <section className="sg sg--closing" data-tone="dark" aria-label={slide.title}>
      <div className="sg-card sg-card--dark sg-closing">
        <div className="sg-closing__text">
          <p className="sg-eyebrow">{content.eyebrow}</p>
          <p className="sg-closing__name">{content.name}</p>
          <p className="sg-closing__role">{content.role}</p>
          <p className="sg-closing__link">
            {/* A local file of LinkedIn's "in" mark (public/logos/linkedin.svg). */}
            {/* eslint-disable-next-line @next/next/no-img-element */}
            <img src="/logos/linkedin.svg" alt="LinkedIn" width={40} height={40} />
            <span>{content.link}</span>
          </p>
        </div>
        <p className="sg-wordmark sg-closing__wordmark" aria-label="Slalom">
          slalom
        </p>
      </div>
      <figure className="sg-qr">
        {/* Generated by pnpm qr (scripts/qr.mts) for the LinkedIn URL; whole stage px per module. */}
        <span className="sg-qr__frame">
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img className="sg-qr__code" src="/qr/linkedin.svg" alt={`QR code for ${content.url}`} />
        </span>
        <figcaption className="sg-qr__caption">{content.caption}</figcaption>
      </figure>
    </section>
  );
}
